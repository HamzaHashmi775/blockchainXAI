def table7():
    cross = load("cross_domain")
    lines = ["# Table 7 — Cross-domain comparison (H6)", "",
             "Relative improvement (proposed − baseline)/|baseline| and verdict per domain; "
             "H6 holds for an outcome when both domains give the same verdict. Domains are not "
             "pooled.", "",
             "| Agents | Outcome | Pharma rel. | Pharma verdict | Energy rel. | Energy verdict "
             "| Same verdict |", "|---|---|---|---|---|---|---|"]
    for arm, label in (("classical", "classical (n = 10)"), ("llm", "LLM (n = 5)")):
        c = cross["arms"][arm]["comparisons"]["proposed_vs_baseline"]
        for o in CONFIRMATORY:
            row = c["outcomes"][o]
            lines.append(f"| {label} | {LABEL[o]} | "
                         f"{row['pharma']['relative_improvement']:+.1%} | "
                         f"{row['pharma']['verdict']} | "
                         f"{row['energy']['relative_improvement']:+.1%} | "
                         f"{row['energy']['verdict']} | "
                         f"{'yes' if c['h6'][o]['same_verdict'] else 'no'} |")
    lines += [""] + [f"- {arm}: H6 holds for "
                     f"{len(cross['arms'][arm]['comparisons']['proposed_vs_baseline']['h6_holds_for'])}"
                     " of 3 outcomes" for arm in cross["arms"]]
    lines += ["", SOURCE.format("cross_domain.json")]
    return "table7_cross_domain.md", lines


BUILDERS = (table1, table2, table3, table4, table5, table6, table7)


def main():
    for build in BUILDERS:
        name, lines = build()
        (TABLES / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("wrote tables/" + name)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
