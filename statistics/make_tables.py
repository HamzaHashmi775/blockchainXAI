"""Paper tables 1-7 (CLAUDE.md step 35), generated from saved results only.

    python statistics/make_tables.py

Reads data/metadata/datasets.json, data/processed/{domain}/scenarios_meta.json, the raw files
(row counts only) and results/summaries/*.json. Writes tables/table{1..7}_*.md. No number is
typed in by hand; the descriptive text in Table 1 restates the frozen protocol (sections 2,
3 and 11) and names its section.
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SUMMARIES = ROOT / "results" / "summaries"
TABLES = ROOT / "tables"
DOMAINS = ("pharma", "energy")
CONFIRMATORY = ("fidelity", "evidence_support", "manipulation")
SECONDARY = ("collective_accuracy", "decision_quality", "collective_utility",
             "manipulation_success", "consistency")
LABEL = {"fidelity": "Fidelity F", "evidence_support": "Evidence support E",
         "manipulation": "Manipulation M", "collective_accuracy": "Collective accuracy",
         "decision_quality": "Decision quality D", "collective_utility": "Collective utility",
         "manipulation_success": "Manipulation success", "consistency": "Consistency"}
SOURCE = "Source: `results/summaries/{}`, generated by `statistics/make_tables.py`."


def load(name):
    return json.loads((SUMMARIES / f"{name}.json").read_text())


def p_fmt(p):
    if p is None or p != p:  # nan
        return "—"
    return "< 0.0001" if p < 0.0001 else f"{p:.4f}"


def ms(d):
    return f"{d['mean']:.3f} ± {d['sd']:.3f}"


def diff_cell(c):
    return f"{c['mean_difference']:+.3f} [{c['ci_low']:+.3f}, {c['ci_high']:+.3f}]"


def effect(c):
    return f"{c['effect_size_name'].replace('cohen_dz', 'd_z').replace('rank_biserial', 'r_rb')}" \
           f" = {c['effect_size']:.2f}"


