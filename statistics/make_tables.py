def table6():
    prov = load("provenance")
    env = prov["environment"]
    lines = ["# Table 6 — Blockchain verification and overhead", "",
             f"Local chain: {env['node']}, Solidity {env['contract']['solc']}; "
             f"{prov['records']:,} records (LLM main runs, both domains). Integrity, not truth; "
             "local-node overhead excludes consensus, block time and network delay.", "",
             "| Group | Records | VALID | TAMPERED | MISSING | Rate |", "|---|---|---|---|---|---|"]
    ver = prov["verification"]
    for g, v in ver.items():
        if not isinstance(v, dict):
            continue
        n = sum(v.values())
        if g in prov["detection_rate"]:
            rate = f"detected {prov['detection_rate'][g]:.3f}"
        elif g == "below_resolution":
            rate = f"detected {v['TAMPERED'] / n:.3f} (by design)"
        else:
            rate = f"false positive {v['TAMPERED'] / n:.3f}"
        lines.append(f"| {g.replace('_', ' ')} | {n:,} | {v['VALID']:,} | {v['TAMPERED']:,} | "
                     f"{v['MISSING']:,} | {rate} |")
    lines += ["", f"Record never written: {ver['never_written']}. Contract rules: overwrite "
                  f"attempts accepted {ver['overwrite_accepted']} of {ver['guard_attempts']}; "
                  f"writes from another account accepted {ver['foreign_write_accepted']} of "
                  f"{ver['guard_attempts']}."]
    lines += ["", "| Batch size | Transactions | Gas / record | Write ms / tx (median) | "
              "Verify ms / record |", "|---|---|---|---|---|"]
    for b, o in prov["overhead"].items():
        lines.append(f"| {b} | {o['transactions']:,} | {o['gas_per_record']:,.0f} | "
                     f"{1000 * o['write_seconds_per_transaction_median']:.1f} | "
                     f"{1000 * o['verify_seconds_per_record']:.1f} |")
    lines += ["", f"Storage: {prov['onchain_storage_bytes_per_record']} bytes on-chain per record "
                  f"vs {prov['offchain_bytes_per_record']:.0f} bytes off-chain. Full run: "
                  f"{prov['record_transactions']} transactions, "
                  f"{prov['record_gas_total'] / prov['records']:,.0f} gas per record. "
                  "Mean write latency for batch size 10 includes an unexplained one-off stall "
                  "(see `tables/provenance.md`); the median is reported here.", "",
              SOURCE.format("provenance.json")]
    return "table6_blockchain.md", lines


