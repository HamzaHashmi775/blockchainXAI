def comparison_table(title, comparison, metrics, note):
    lines = [f"# {title}", "", note, "",
             "| Domain | Metric | Baseline | Treatment | Δ [95% CI] | Rel. | Test | p (Holm) "
             "| Effect | Verdict |", "|---|---|---|---|---|---|---|---|---|---|"]
    for d in DOMAINS:
        data = load(f"{d}_main")
        treatment = comparison.split("_vs_")[0]
        for m in metrics:
            c = data["comparisons"][comparison][m]
            p = c.get("p_holm") if m in CONFIRMATORY else c["p_value"]
            lines.append(
                f"| {d} | {LABEL[m]} | {ms(data['descriptive'][m]['baseline'])} | "
                f"{ms(data['descriptive'][m][treatment])} | {diff_cell(c)} | "
                f"{c['relative_improvement']:+.1%} | {c['test']} | {p_fmt(p)}"
                f"{'' if m in CONFIRMATORY else ' (unadj.)'} | {effect(c)} | "
                f"{c.get('verdict') or '—'} |")
    lines += ["", SOURCE.format("{pharma,energy}_main.json")]
    return lines


def table2():
    note = ("Classical agents, n = 10 paired seeds; mean ± SD over seeds. Confirmatory family "
            "F, E, M: Holm-adjusted p and the pre-declared verdict (improved = Holm p < 0.05 in "
            "the hypothesised direction and |rel.| ≥ 5 %). Other rows are secondary, unadjusted, "
            "without verdict. Rel. = (proposed − baseline)/|baseline|; for M and manipulation "
            "success a negative value is the improvement.")
    return "table2_baseline_vs_proposed.md", comparison_table(
        "Table 2 — Baseline vs proposed", "proposed_vs_baseline",
        CONFIRMATORY + SECONDARY, note)


def table3():
    lines = ["# Table 3 — Explanation quality: fidelity, evidence support, consistency", "",
             "Mean ± SD over seeds, metrics averaged over agents and the evaluation window. "
             "Classical agents n = 10; LLM agents (qwen2.5:7b, ω 0.5) n = 5 (no consistency "
             "metric for LLM runs).", "",
             "| Agents | Domain | System | Fidelity F | Evidence support E | Consistency |",
             "|---|---|---|---|---|---|"]
    for d in DOMAINS:
        desc = load(f"{d}_main")["descriptive"]
        for s in ("baseline", "ablation", "proposed"):
            lines.append(f"| classical | {d} | {s} | {ms(desc['fidelity'][s])} | "
                         f"{ms(desc['evidence_support'][s])} | {ms(desc['consistency'][s])} |")
    for d in DOMAINS:
        desc = load(f"{d}_llm")["main"]["descriptive"]
        for s in ("baseline", "ablation", "proposed"):
            lines.append(f"| LLM | {d} | {s} | {ms(desc['fidelity'][s])} | "
                         f"{ms(desc['evidence_support'][s])} | — |")
    lines += ["", SOURCE.format("{pharma,energy}_main.json, {pharma,energy}_llm.json")]
    return "table3_explanation_quality.md", lines


def table4():
    note = ("Incentive ablation: game + XAI + explanation-aware incentive (no reputation, no "
            "chain) vs baseline. Classical agents, n = 10. Rules as Table 2. The last block "
            "compares proposed with ablation descriptively (the reputation increment; not a "
            "pre-declared test).")
    lines = comparison_table("Table 4 — Incentive ablation", "ablation_vs_baseline",
                             CONFIRMATORY + ("collective_accuracy", "manipulation_success"),
                             note)
    lines = lines[:-2]
    lines += ["", "**Proposed − ablation (descriptive, reputation increment)**", "",
              "| Domain | Metric | Ablation | Proposed | Δ mean |", "|---|---|---|---|---|"]
    for d in DOMAINS:
        desc = load(f"{d}_main")["descriptive"]
        for m in CONFIRMATORY + ("collective_accuracy", "manipulation_success"):
            a, p = desc[m]["ablation"], desc[m]["proposed"]
            lines.append(f"| {d} | {LABEL[m]} | {ms(a)} | {ms(p)} | "
                         f"{p['mean'] - a['mean']:+.3f} |")
    lines += ["", SOURCE.format("{pharma,energy}_main.json")]
    return "table4_ablation.md", lines


