def table5():
    final = load("final_statistics")["H4"]["classical"]
    lines = ["# Table 5 — Robustness to malicious agents", "",
             "Classical agents, n = 10 seeds; mean ± SD. Malicious agents always play "
             "*manipulative*. H4 primary: mean accuracy degradation over 10–40 %, proposed − "
             "baseline (negative = proposed degrades less), paired, two-sided, α 0.05.", ""]
    for d in DOMAINS:
        adv = load(f"{d}_adversarial")
        fr = adv["fractions"]
        lines += [f"## {d}", "", "| Metric | System | " +
                  " | ".join(f"{float(f):.0%}" for f in fr) + " |",
                  "|---|---|" + "---|" * len(fr)]
        for m in ("collective_accuracy", "fidelity", "evidence_support", "manipulation",
                  "manipulation_success"):
            for s in adv["systems"]:
                lines.append(f"| {LABEL[m]} | {s} | " + " | ".join(
                    ms(adv["descriptive"][m][s][f]) for f in fr) + " |")
        h4 = final[d]
        fried = adv["friedman_accuracy_across_fractions"]
        lines += ["", f"H4 primary: Δ {h4['mean_difference']:+.4f} "
                      f"[{h4['ci_low']:+.4f}, {h4['ci_high']:+.4f}], {h4['test']}, "
                      f"p {p_fmt(h4['p_value'])} → **{h4['verdict']}**. Friedman on accuracy "
                      "across shares: " + "; ".join(
                          f"{s} χ² {fried[s]['statistic']:.2f}, p {p_fmt(fried[s]['p_value'])}"
                          for s in adv["systems"]) + ".", "",
                  "Collusion (2 colluders + 3 honest vs no collusion; with − without, unadjusted p):",
                  "", "| System | Quantity | Δ | p |", "|---|---|---|---|"]
        for s in adv["systems"]:
            for q in ("collective_accuracy", "manipulation_success", "colluders_reward",
                      "colluders_payoff", "honest_agents_payoff"):
                c = adv["collusion"][s][q]
                lines.append(f"| {s} | {q.replace('_', ' ')} | {c['mean_difference']:+.3f} | "
                             f"{p_fmt(c['p_value'])} |")
        lines.append("")
    lines.append(SOURCE.format("{pharma,energy}_adversarial.json, final_statistics.json"))
    return "table5_malicious_agents.md", lines


